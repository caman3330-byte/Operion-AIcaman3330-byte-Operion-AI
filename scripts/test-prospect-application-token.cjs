const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const crypto = require('node:crypto');
const file = path.resolve(__dirname, '../apps/dashboard/lib/acquisition/application-token.ts');
const output = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const moduleBox = { exports: {} };
vm.runInNewContext(output, { module: moduleBox, exports: moduleBox.exports, require: (id) => id === 'node:crypto' ? crypto : require(id), Buffer, RegExp, String });
const token = moduleBox.exports.createProspectApplicationToken();
const second = moduleBox.exports.createProspectApplicationToken();
assert.match(token.token, /^opas_[A-Za-z0-9_-]{42,}$/);
assert.notEqual(token.token, second.token);
assert.match(token.tokenHash, /^[a-f0-9]{64}$/);
assert.equal(moduleBox.exports.applicationTokenHashMatches(token.token, token.tokenHash), true);
assert.equal(moduleBox.exports.applicationTokenHashMatches(second.token, token.tokenHash), false);
assert.equal(moduleBox.exports.isProspectApplicationToken(token.token), true);
assert.equal(moduleBox.exports.isProspectApplicationToken('opas_guess'), false);
console.log('prospect application token tests passed');
